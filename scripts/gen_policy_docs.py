#!/usr/bin/env python3
"""Generate the policy tables embedded in the docs from src/kitna/data/policy.tsv.

Usage: python scripts/gen_policy_docs.py          # rewrite docs/_generated/*.md
       python scripts/gen_policy_docs.py --check  # exit 1 if they are out of date
"""
from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
POLICY = ROOT / "src" / "kitna" / "data" / "policy.tsv"
OUT = ROOT / "docs" / "_generated"

#: the wording of each open question (ids match docs/taxonomy.md section 5)
QUESTIONS = {
    "Q2": "Is `do chaar` really a 2-4 range, or just 'a few'?",
    "Q3": "Are the usual hours for each day-part word right? Should a bare hour be flagged?",
    "Q3b": "Do `shaam 4 baje` (16:00) and `raat 2 baje` (02:00) match real speech?",
    "Q4": "Is `kal chhutti hai` / `kal ka ticket book kar do` future? How much weaker than a real future verb?",
    "Q5": "Is a bare `paune` (0.75) natural, or only `paun` / `pauna`?",
    "Q6": "A bare weekday said on that weekday: today, next week, or flag both?",
    "Q7": "`agle shanivaar` said on a Thursday: the coming Saturday or next week's?",
    "Q8": "A date with no year (or no month) and no tense cue: flag both, or assume the next one?",
    "Q9": "Is `saade ek` / `saade do` ever said?",
    "Q9b": "Is it `narso` or `tarso` where you live, and is it common?",
    "Q12": "`ek baar` means 'once': should the parser return nothing, or the number 1?",
    "Q11": "Should `prefer='future'` also resolve a bare `kal` / `parso`?",
    "Q13": "Said at 10 in the morning: does `aaj 2 baje call karungi` always mean 2 in the afternoon? "
           "And does `aaj 5 baje pahuncha tha` always mean 5 in the morning?",
}


def rows() -> list[list[str]]:
    out = []
    for line in POLICY.read_text(encoding="utf-8").splitlines():
        if line.strip() and not line.startswith("#"):
            cols = [c.strip() for c in line.split("\t")]
            out.append((cols + ["", ""])[:4])
    return out


def cell(s: str) -> str:
    return s.replace("|", "\\|") or " "


def render() -> dict[str, str]:
    data = rows()
    head = "<!-- generated by scripts/gen_policy_docs.py from src/kitna/data/policy.tsv; do not edit -->\n\n"
    full = head + "| Key | Current value | Open question | Meaning |\n|---|---|---|---|\n" + "".join(
        f"| `{k}` | `{cell(v)}` | {q if q != '-' else 'settled'} | {cell(m)} |\n" for k, v, q, m in data)
    by_q: dict[str, list[tuple[str, str]]] = {}
    for k, v, q, _ in data:
        if q != "-":
            by_q.setdefault(q, []).append((k, v))
    missing = sorted(set(by_q) - set(QUESTIONS))
    if missing:
        raise SystemExit(f"gen_policy_docs.py: no question text for {missing}")
    order = sorted(by_q, key=lambda q: (int("".join(c for c in q if c.isdigit())), q))
    cols = "| # | Question for a native speaker | Policy rows it controls (current value) |\n|---|---|---|\n"
    opened = head + cols + "".join(
        f"| {q} | {QUESTIONS[q]} | " + "<br>".join(f"`{k}` = `{cell(v)}`" for k, v in by_q[q]) + " |\n" for q in order)
    return {"policy_table.md": full, "open_questions_table.md": opened}


def main() -> int:
    check = "--check" in sys.argv
    stale = False
    for name, text in render().items():
        path = OUT / name
        if check:
            if not path.exists() or path.read_text(encoding="utf-8") != text:
                print(f"out of date: {path.relative_to(ROOT)} (run scripts/gen_policy_docs.py)", file=sys.stderr)
                stale = True
        else:
            OUT.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding="utf-8")
            print(f"wrote {path.relative_to(ROOT)}")
    return 1 if stale else 0


if __name__ == "__main__":
    raise SystemExit(main())
